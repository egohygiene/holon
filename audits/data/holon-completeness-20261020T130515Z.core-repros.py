#!/usr/bin/env python3
"""Bounded, temp-only reproductions against a caller-selected Holon source."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, sort_keys=True, indent=2) + "\n", encoding="utf-8")


def fixture(root: Path, source_root: Path) -> tuple[Path, Path, Path, dict]:
    from holon_contract import resolve_manifest

    target, pack, aether = root / "consumer", root / "pack", root / "aether"
    target.mkdir()
    pack.mkdir()
    agent_path = aether / "github/repository/.github/agents/architect.agent.md"
    agent_path.parent.mkdir(parents=True)
    agent_bytes = b"---\nname: Architect\n---\n\n# Architect\n"
    agent_path.write_bytes(agent_bytes)
    sha = digest(agent_bytes)
    write_json(aether / "projections/manifest.v1.json", {
        "schema_version": "aether.projection-manifest/v1",
        "interface_version": "1.0.0",
        "providers": [{"id": "github-copilot", "status": "native", "adapter": "github-agent-markdown", "shares_output_with": None, "unsupported_features": []}],
        "outputs": [{"path": "dist/github/repository/.github/agents/architect.agent.md", "sha256": sha}],
    })
    write_json(aether / "release/release-manifest.v1.json", {"repository_release_tag": "v0.1.0", "artifacts": []})
    write_json(aether / "release/release-provenance.v1.json", {
        "repository_release_tag": "v0.1.0", "commit_sha": "0123456789abcdef0123456789abcdef01234567",
        "output_files": [{"path": "github/repository/.github/agents/architect.agent.md", "sha256": sha}],
    })
    catalog = json.loads((source_root / "catalog/foundation.json").read_text())
    manifest = json.loads((source_root / "examples/library.manifest.json").read_text())
    resolved, errors = resolve_manifest(catalog, manifest)
    assert not errors and resolved is not None, errors
    return target, pack, aether, resolved


def cli(source_root: Path, *args: str) -> dict:
    result = subprocess.run([sys.executable, str(source_root / "tools/holon_materialize.py"), *args], cwd=source_root, capture_output=True, text=True, check=False)
    # Output paths are intentionally omitted from the public normalized result.
    return {"exit_code": result.returncode, "stderr": result.stderr.strip()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    args = parser.parse_args()
    source_root = args.source_root.resolve()
    sys.path.insert(0, str(source_root / "tools"))
    from holon_contract import resolve_manifest
    from materialization import build_plan, render_plan, rollback_target, verify_target
    from materialization.common import MaterializationError, render_source_bytes

    results = {}
    with tempfile.TemporaryDirectory(prefix="holon-core-audit-") as temp:
        root = Path(temp)

        # A dangling consumer link bypasses the lexical .git prohibition.
        case = root / "symlink"
        case.mkdir()
        target, pack, aether, resolved = fixture(case, source_root)
        (target / ".git").mkdir()
        (target / "generated.txt").symlink_to(".git/audit-sentinel")
        (pack / "generated.txt").write_text("synthetic generated bytes\n")
        plan, _ = build_plan(resolved, target, render_source=pack, aether_source=aether)
        plan_path = case / "plan.json"
        write_json(plan_path, plan)
        render_result = cli(source_root, "render", "--plan", str(plan_path), "--target", str(target), "--render-source", str(pack), "--aether-source", str(aether))
        results["generic_consumer_symlink_into_git"] = {
            "plan_action": next(x["action"] for x in plan["operations"] if x["path"] == "generated.txt"),
            "render_exit_code": render_result["exit_code"],
            "protected_git_file_created": (target / ".git/audit-sentinel").is_file(),
            "protected_git_file_content": (target / ".git/audit-sentinel").read_text(),
            "consumer_link_retained": (target / "generated.txt").is_symlink(),
            "verify_errors": verify_target(target),
        }

        # Backup namespace paths are not checked with target_path before writes.
        case = root / "backup-link"
        case.mkdir()
        target, pack, aether, resolved = fixture(case, source_root)
        outside = case / "outside"
        outside.mkdir()
        (target / ".holon").mkdir()
        (target / ".holon/backups").symlink_to(outside, target_is_directory=True)
        (pack / "owned.txt").write_text("synthetic\n")
        plan, _ = build_plan(resolved, target, render_source=pack, aether_source=aether)
        state = render_plan(plan, target, render_source=pack, aether_source=aether)
        rollback_error = None
        try:
            rollback_target(target)
        except MaterializationError as error:
            rollback_error = str(error)
        results["generic_backup_symlink_outside_target"] = {
            "outside_backup_files": sorted(p.relative_to(outside).as_posix() for p in outside.rglob("*") if p.is_file()),
            "outside_backup_count": sum(p.is_file() for p in outside.rglob("*")),
            "state_published": (target / ".holon/materialization-state.v1.json").is_file(),
            "rollback_error": rollback_error,
        }

        # Missing backup is discovered only after a different operation was undone.
        case = root / "partial-rollback"
        case.mkdir()
        target, pack, aether, resolved = fixture(case, source_root)
        (pack / "a.txt").write_text("before\n")
        plan, _ = build_plan(resolved, target, render_source=pack, aether_source=aether)
        render_plan(plan, target, render_source=pack, aether_source=aether)
        (pack / "a.txt").write_text("after\n")
        (pack / "z.txt").write_text("new file\n")
        plan, _ = build_plan(resolved, target, render_source=pack, aether_source=aether)
        state = render_plan(plan, target, render_source=pack, aether_source=aether)
        state_before_failure = (target / ".holon/materialization-state.v1.json").read_bytes()
        backup_root = (target / state["rollback_manifest"]).parent
        (backup_root / "files/a.txt").unlink()
        outcome = cli(source_root, "rollback", "--target", str(target))
        results["generic_rollback_missing_backup_partially_mutates"] = {
            "rollback_exit_code": outcome["exit_code"], "rollback_stderr": outcome["stderr"],
            "created_z_exists_after_failed_rollback": (target / "z.txt").exists(),
            "updated_a_after_failed_rollback": (target / "a.txt").read_text(),
            "current_state_unchanged": (target / ".holon/materialization-state.v1.json").read_bytes() == state_before_failure,
            "verify_errors_after_failed_rollback": verify_target(target),
        }

        # Unsupported required shape fields are accepted by the actual CLI.
        manifest = json.loads((source_root / "examples/library.manifest.json").read_text())
        manifest["preserve_paths"] = "README.md"
        del manifest["repository"]
        path = root / "invalid-manifest.json"
        write_json(path, manifest)
        outcome = subprocess.run([sys.executable, str(source_root / "tools/holon_contract.py"), "--catalog", str(source_root / "catalog/foundation.json"), "validate", "--manifest", str(path)], cwd=source_root, capture_output=True, text=True, check=False)
        resolved, errors = resolve_manifest(json.loads((source_root / "catalog/foundation.json").read_text()), manifest)
        results["foundation_manifest_schema_parity"] = {
            "cli_exit_code": outcome.returncode, "cli_stdout": outcome.stdout.strip(),
            "resolver_errors": errors, "resolved_repository": resolved["repository"],
            "resolved_preserve_paths": resolved["preserve_paths"],
            "declared_schema_requires_repository": "repository" in json.loads((source_root / "schemas/foundation-manifest.v1.schema.json").read_text())["required"],
            "declared_preserve_paths_type": "array",
        }

        # Unknown scalar tokens fail; unknown JSON tokens silently survive.
        token_outcome = {"json_result": render_source_bytes(b"const value = {{parameter_json.missing}};\n", {"repository": "fixture/repo", "repository_class": "library", "security_level": "baseline", "parameters": {}}, "config.ts").decode()}
        try:
            render_source_bytes(b"value={{parameter.missing}}\n", {"repository": "fixture/repo", "repository_class": "library", "security_level": "baseline", "parameters": {}}, "config.txt")
        except MaterializationError:
            token_outcome["scalar_missing_rejected"] = True
        results["unresolved_json_template_token"] = token_outcome
        case = root / "unresolved-json-token"
        case.mkdir()
        target, pack, aether, resolved = fixture(case, source_root)
        (pack / "config.ts").write_text("const value = {{parameter_json.missing}};\n")
        plan_path = case / "plan.json"
        plan_result = cli(source_root, "plan", "--manifest", str(source_root / "examples/library.manifest.json"), "--target", str(target), "--render-source", str(pack), "--aether-source", str(aether), "--output", str(plan_path))
        render_result = cli(source_root, "render", "--plan", str(plan_path), "--target", str(target), "--render-source", str(pack), "--aether-source", str(aether))
        token_outcome.update({"plan_cli_exit_code": plan_result["exit_code"], "render_cli_exit_code": render_result["exit_code"], "generated_config": (target / "config.ts").read_text()})

        # Current generic output is checked against its declared public schema.
        case = root / "schema"
        case.mkdir()
        target, pack, aether, resolved = fixture(case, source_root)
        plan, _ = build_plan(resolved, target, render_source=pack, aether_source=aether)
        state = render_plan(plan, target, render_source=pack, aether_source=aether)
        schema = json.loads((source_root / "schemas/materialization-plan.v1.schema.json").read_text())
        results["generic_output_schema_parity"] = {
            "emitted_input_keys": sorted(plan["inputs"]),
            "declared_input_properties": sorted(schema["properties"]["inputs"]["properties"]),
            "declared_inputs_additional_properties": schema["properties"]["inputs"]["additionalProperties"],
            "state_uses_same_inputs": state["inputs"] == plan["inputs"],
        }
        try:
            from jsonschema import Draft202012Validator, RefResolver
        except ImportError:
            results["generic_output_schema_parity"]["standard_validator"] = "unavailable in this interpreter"
        else:
            results["generic_output_schema_parity"]["standard_validator"] = "Draft202012Validator"
            results["generic_output_schema_parity"]["plan_schema_errors"] = sorted(error.message for error in Draft202012Validator(schema).iter_errors(plan))
            state_schema = json.loads((source_root / "schemas/materialization-state.v1.schema.json").read_text())
            resolver = RefResolver.from_schema(state_schema, store={schema["$id"]: schema})
            results["generic_output_schema_parity"]["state_schema_errors"] = sorted(error.message for error in Draft202012Validator(state_schema, resolver=resolver).iter_errors(state))
            manifest_schema = json.loads((source_root / "schemas/foundation-manifest.v1.schema.json").read_text())
            results["foundation_manifest_schema_parity"]["standard_validator"] = "Draft202012Validator"
            results["foundation_manifest_schema_parity"]["manifest_schema_errors"] = sorted(error.message for error in Draft202012Validator(manifest_schema).iter_errors(manifest))

    print(json.dumps(results, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
